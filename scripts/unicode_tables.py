"""Write side_vim/_unicode_data.py from real vim.

For every code point, asks vim for its character class (charclass(), what the word
motions use) and its width in screen cells (strdisplaywidth()). Run it by hand when
moving to a new vim version, and commit the result:

    uv run python scripts/unicode_tables.py

Needs vim with +eval on the PATH. Runs it with no config (vim -u NONE).
"""

import subprocess
import sys
import tempfile
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "side_vim" / "_unicode_data.py"

# Writes "code point, class, width" each time the class or the width changes.
# Surrogates aren't characters; they keep the values from before them.
VIM_SCRIPT = """
let out = []
let last = [-1, -1]
for c in range(1, 0x10ffff)
  if c >= 0xd800 && c <= 0xdfff
    continue
  endif
  let s = nr2char(c)
  let now = [charclass(s), strdisplaywidth(s)]
  if now != last
    call add(out, c .. ' ' .. now[0] .. ' ' .. now[1])
    let last = now
  endif
endfor
call writefile(out, '{out}')
call writefile(execute('version')->split("\\n"), '{ver}')
qa!
"""


def vim_version(lines: list[str]) -> str:
    """Like "vim 9.1, patches 1-16, 647" from the output of :version."""
    number = next(line for line in lines if "IMproved" in line).split()[4]
    patches = next((line for line in lines if line.startswith("Included patches")), "")
    patches = patches.partition(":")[2].strip()
    return f"vim {number}, patches {patches}" if patches else f"vim {number}"


def runs(rows: list[tuple[int, int]]) -> tuple[list[int], list[int]]:
    """Squeeze (code point, value) rows into the code points where the value changes."""
    starts: list[int] = [0]
    values: list[int] = [0]  # code point 0 stands for the end of a line: blank, no width
    for cp, value in rows:
        if value != values[-1]:
            starts.append(cp)
            values.append(value)
    return starts, values


def wrap(name: str, numbers: list[int]) -> str:
    lines = [f"{name} = ("]
    row: list[str] = []
    for n in numbers:
        row.append(f"{n},")
        if len(" ".join(row)) > 88:
            lines.append("    " + " ".join(row[:-1]))
            row = row[-1:]
    if row:
        lines.append("    " + " ".join(row))
    lines.append(")")
    return "\n".join(lines)


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        out, ver, script = Path(tmp, "out.txt"), Path(tmp, "ver.txt"), Path(tmp, "s.vim")
        script.write_text(VIM_SCRIPT.replace("{out}", str(out)).replace("{ver}", str(ver)))
        subprocess.run(
            ["vim", "-u", "NONE", "-i", "NONE", "-N", "-n", "-Es", "-S", str(script)],
            check=False,
            timeout=600,
        )
        if not out.exists():
            print("vim didn't write its output; is vim with +eval installed?", file=sys.stderr)
            return 1
        rows = [tuple(map(int, line.split())) for line in out.read_text().splitlines()]
        version = vim_version(ver.read_text().splitlines())

    class_starts, class_values = runs([(cp, cls) for cp, cls, _ in rows])
    width_starts, width_values = runs([(cp, width) for cp, _, width in rows])
    OUT.write_text(
        f'"""Vim\'s character classes and cell widths for every code point.\n\n'
        f"Generated by scripts/unicode_tables.py from {version}.\n"
        f'Don\'t edit by hand.\n"""\n\n'
        "# A code point's value is VALUES[i] for the last STARTS[i] at or below it.\n\n"
        f"{wrap('CLASS_STARTS', class_starts)}\n\n"
        f"{wrap('CLASS_VALUES', class_values)}\n\n"
        f"{wrap('WIDTH_STARTS', width_starts)}\n\n"
        f"{wrap('WIDTH_VALUES', width_values)}\n"
    )
    print(f"wrote {OUT}: {len(class_starts)} class runs, {len(width_starts)} width runs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
