"""Write side_vim/_digraphs.py from real vim: its default digraphs, for r and Ctrl+K.

Run it by hand when moving to a new vim version, and commit the result:

    uv run python scripts/digraph_table.py

Needs vim with +eval on the PATH. Runs it with no config (vim -u NONE).
"""

import json
import subprocess
import sys
import tempfile
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "side_vim" / "_digraphs.py"

VIM_SCRIPT = """
call writefile([json_encode(digraph_getlist(1))], '{out}')
call writefile(execute('version')->split("\\n"), '{ver}')
qa!
"""


def vim_version(lines: list[str]) -> str:
    """Like "vim 9.1, patches 1-16, 647" from the output of :version."""
    number = next(line for line in lines if "IMproved" in line).split()[4]
    patches = next((line for line in lines if line.startswith("Included patches")), "")
    patches = patches.partition(":")[2].strip()
    return f"vim {number}, patches {patches}" if patches else f"vim {number}"


def quote(text: str) -> str:
    """A Python string literal, with invisible characters escaped. Double quotes,
    unless the text has one and no single quote, as ruff format writes it."""
    mark = "'" if '"' in text and "'" not in text else '"'
    out: list[str] = []
    for ch in text:
        if ch in (mark, "\\"):
            out.append("\\" + ch)
        elif ch.isprintable():
            out.append(ch)
        elif ord(ch) <= 0xFF:
            out.append(f"\\x{ord(ch):02x}")
        else:
            out.append(f"\\u{ord(ch):04x}")
    return mark + "".join(out) + mark


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        out, ver, script = Path(tmp, "out.json"), Path(tmp, "ver.txt"), Path(tmp, "s.vim")
        script.write_text(VIM_SCRIPT.replace("{out}", str(out)).replace("{ver}", str(ver)))
        subprocess.run(
            ["vim", "-u", "NONE", "-i", "NONE", "-N", "-n", "-Es", "-S", str(script)],
            check=False,
            timeout=60,
        )
        if not out.exists():
            print("vim didn't write its output; is vim with +eval installed?", file=sys.stderr)
            return 1
        pairs = json.loads(out.read_text(encoding="utf-8"))
        version = vim_version(ver.read_text().splitlines())

    rows = "".join(f"    {quote(keys)}: {quote(char)},\n" for keys, char in pairs)
    OUT.write_text(
        f'"""Vim\'s default digraphs: the two characters typed after Ctrl+K, and the\n'
        "character they make.\n\n"
        f"Generated by scripts/digraph_table.py from {version}.\n"
        f'Don\'t edit by hand.\n"""\n\n'
        "# vim keeps a NUL in the text as a line feed, so NU makes one too.\n"
        f"DIGRAPHS = {{\n{rows}}}\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT}: {len(pairs)} digraphs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
